import fs from 'node:fs';
import path from 'node:path';

export const GENERATOR_SIGNATURE = 'Generated by ai-project-structure-template';
export const GENERATOR_HEADER = `<!-- ${GENERATOR_SIGNATURE}. Do not edit directly. Edit canonical .agents/ sources, then run 'node bin/create-preset.mjs sync'. -->`;

export function isManagedFile(filePath) {
  if (!fs.existsSync(filePath)) return false;
  try {
    const head = fs.readFileSync(filePath, 'utf8').slice(0, 500);
    return (
      head.includes(GENERATOR_SIGNATURE) ||
      head.includes('Generated from .agents/') ||
      head.includes('Generated from canonical') ||
      head.includes('Generated adapter summary')
    );
  } catch {
    return false;
  }
}

export function writeFileSafe(targetPath, content, options = {}) {
  const { dryRun = false, force = false } = options;
  const dir = path.dirname(targetPath);

  if (fs.existsSync(targetPath)) {
    const existing = fs.readFileSync(targetPath, 'utf8');
    if (existing === content) {
      return { status: 'unchanged', path: targetPath };
    }
    // If not managed and force not set, avoid clobbering user file
    if (!force && !isManagedFile(targetPath)) {
      return { status: 'skipped_user_file', path: targetPath };
    }
    if (!dryRun) {
      fs.writeFileSync(targetPath, content, 'utf8');
    }
    return { status: 'updated', path: targetPath };
  }

  if (!dryRun) {
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
    }
    fs.writeFileSync(targetPath, content, 'utf8');
  }
  return { status: 'created', path: targetPath };
}

export function writeManagedFileSafe(targetPath, content, options = {}) {
  return writeFileSafe(targetPath, addManagedHeader(content, targetPath), options);
}

export function copyDirectorySafe(srcDir, destDir, options = {}) {
  const { dryRun = false, force = false, managed = false } = options;
  const results = [];

  if (!fs.existsSync(srcDir)) return results;

  function copyRecursive(currentSrc, currentDest) {
    const entries = fs.readdirSync(currentSrc, { withFileTypes: true });
    for (const entry of entries) {
      const srcPath = path.join(currentSrc, entry.name);
      const destPath = path.join(currentDest, entry.name);

      if (entry.isDirectory()) {
        copyRecursive(srcPath, destPath);
      } else if (entry.isFile()) {
        let content = fs.readFileSync(srcPath, 'utf8');
        if (managed) content = addManagedHeader(content, destPath);
        results.push(writeFileSafe(destPath, content, { dryRun, force }));
      }
    }
  }

  copyRecursive(srcDir, destDir);
  return results;
}

function addManagedHeader(content, targetPath) {
  if (content.includes(GENERATOR_SIGNATURE)) return content;

  if (/\.ya?ml$/i.test(targetPath)) {
    return `# ${GENERATOR_SIGNATURE}\n${content}`;
  }

  if (/\.md$/i.test(targetPath)) {
    const frontmatter = content.match(/^---\s*\r?\n[\s\S]*?\r?\n---\s*\r?\n/);
    if (frontmatter) {
      return `${frontmatter[0]}\n${GENERATOR_HEADER}\n\n${content.slice(frontmatter[0].length)}`;
    }
    return `${GENERATOR_HEADER}\n\n${content}`;
  }

  return content;
}

export function safeMergeJson(targetPath, newJsonConfig, options = {}) {
  const { dryRun = false } = options;
  let current = {};

  if (fs.existsSync(targetPath)) {
    const original = fs.readFileSync(targetPath, 'utf8');
    try {
      current = JSON.parse(original);
    } catch (error) {
      throw new Error(`Cannot update ${targetPath}: existing JSON is invalid: ${error.message}`);
    }
  }

  const merged = { ...current };

  for (const [key, value] of Object.entries(newJsonConfig)) {
    if (Array.isArray(value)) {
      const existingArray = Array.isArray(merged[key]) ? merged[key] : [];
      const combined = [...existingArray];
      for (const item of value) {
        if (!combined.includes(item)) {
          combined.push(item);
        }
      }
      merged[key] = combined;
    } else if (value && typeof value === 'object') {
      merged[key] = { ...(merged[key] || {}), ...value };
    } else {
      merged[key] = value;
    }
  }

  const output = JSON.stringify(merged, null, 2) + '\n';
  return writeFileSafe(targetPath, output, { dryRun, force: true });
}
